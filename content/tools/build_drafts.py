def sentences_ok(lines: list[str], eid: str) -> None:
    for s in lines:
        if len(s) > MAX_SENTENCE:
            raise SystemExit(f"{eid}: 문장이 {MAX_SENTENCE}자를 넘음 ({len(s)}자): {s}")


def duration(lines: list[str], quiz) -> int:
    chars = sum(len(re.sub(r"\s", "", s)) for s in lines)
    sec = chars / CHARS_PER_SEC + PAUSE_SEC * len(lines) + (QUIZ_SEC if quiz else 0)
    return int(round(sec / 5.0) * 5)


def main() -> None:
    episodes = []
    for eid, topic, title, min_age, max_age, check, lines, quiz in EPISODES:
        sentences_ok(lines, eid)
        q, choices, answer = quiz
        sentences_ok([q], eid)
        item = {
            "id": eid, "topic": topic, "title": title, "durationSec": duration(lines, quiz),
            "minAge": min_age, "maxAge": max_age, "reviewed": False, "check": check,
            "lines": lines, "quiz": {"question": q, "choices": choices, "answerIndex": answer},
        }
        episodes.append(item)
    missions = [
        {"id": mid, "context": ctx, "title": title, "instructions": ins, "durationSec": dur, "minAge": age, "reviewed": False}
        for mid, ctx, title, ins, dur, age in MISSIONS
    ]
    out = ROOT / "drafts"
    out.mkdir(exist_ok=True)
    note = "검수 전 초안. reviewed=false — 사람이 읽고 고친 뒤에만 true로 바꾼다. check=true는 사실 확인이 필요한 문장이 있음."
    (out / "episodes.json").write_text(json.dumps({"_comment": note, "items": episodes}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "missions.json").write_text(json.dumps({"_comment": note, "items": missions}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"episodes {len(episodes)} (총 {sum(e['durationSec'] for e in episodes)}초), missions {len(missions)}")


if __name__ == "__main__":
    main()
